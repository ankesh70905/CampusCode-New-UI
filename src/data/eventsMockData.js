function dateOffset(days, hour = 17) {
  const date = new Date();
  date.setHours(hour, 0, 0, 0);
  date.setDate(date.getDate() + days);
  return date.toISOString();
}

function createRounds(prefix, offsets, activeIndex = -1) {
  const names = ["Open brief", "Build sprint", "Final showcase"];
  const descriptions = [
    "Read the prompt, choose a direction, and share a short concept note.",
    "Build a working prototype and submit your project details for review.",
    "Present the finished idea, reflect on feedback, and wrap up the event.",
  ];
  return names.map((name, index) => ({
    id: `${prefix}-round-${index + 1}`,
    name,
    description: descriptions[index],
    startsAt: dateOffset(offsets[index]),
    deadlineAt: dateOffset(offsets[index] + 3),
    requirements: [
      "Review the round brief and eligibility notes.",
      "Describe your approach clearly and credit any third-party materials.",
      "Submit before the displayed deadline.",
    ],
    initialStatus: index < activeIndex ? "completed" : index === activeIndex ? "active" : "locked",
  }));
}

